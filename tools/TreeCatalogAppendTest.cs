/// <summary>
/// T6-5 and T6-7 (docs/work-orders/terrain-vegetation/T6.md, A6, A6a and A8): the derived forms (snags 30-35, fallen trees 36-39, stumps 40-42, shrubs 43-54) and the catalog identity rule for appended entries.
/// Generation 1's catalog field and cache identity are unchanged with the derived catalog loaded; the golden rows compare with a missing catalog_appended as none; a synthetic row behind an unused
/// feature moves nothing it should not; the first 30 variants and the base resources match tools/fixtures/tree_catalog_base_golden.json; derived structure, size and regeneration match the manifest; forms 30-42 keep the mesh hashes T6-5 wrote (tools/fixtures/derived_forms_30_42_golden.json); the shrubs are 2-LOD single-foliage-surface forms whose cluster rectangles regenerate.
/// Prints TREE_CATALOG_APPEND=PASS. Headless: tools/run_tests.ps1 -Tests tree_catalog_append_test.
/// </summary>
public partial class TreeCatalogAppendTest : RefCounted
{
    const string BaseGoldenPath = "res://tools/fixtures/tree_catalog_base_golden.json";
    const string BaseResource = "res://resources/trees/prepared/lolipop_catalog.res";
    const string ImpostorResource = "res://resources/trees/prepared/lolipop_impostor_atlas.res";
    const string DerivedGoldenPath = "res://tools/fixtures/derived_forms_30_42_golden.json";
    const string FeatureId = "vegetation.forest_structure";
    const string NewSpecies = "vegetation.new_species";
    const int LodSlots = PreparedDerivedTreeCatalog.LodsPerForm;
    private readonly List<string> _failures = new();
    private void Check(bool ok, string message) { if (!ok && _failures.Count < 40) _failures.Add(message); }
    private static void Detail(string text) => Console.WriteLine("TREE_CATALOG_APPEND_DETAIL " + text);
    private static readonly JsonSerializerOptions Pretty = new() { WriteIndented = true };

    public int Run()
    {
        try
        {
            if (OS.GetCmdlineUserArgs().Contains("--write-base-golden")) { WriteBaseGolden(); return 0; }
            IReadOnlyList<ImportedTreeVariant> baseCatalog = ImportedTreeCatalog.Load();
            DerivedTreeCatalog.Load(); // loaded on purpose: every generation 1 check below runs with it present
            FingerprintChecks(baseCatalog);
            IdentityChecks();
            BaseGoldenChecks(baseCatalog);
            StructureChecks(baseCatalog);
            RegenerationChecks(baseCatalog);
        }
        catch (Exception exception) { _failures.Add("exception: " + exception); }
        if (_failures.Count == 0) { Console.WriteLine("TREE_CATALOG_APPEND=PASS"); return 0; }
        foreach (string failure in _failures) GD.PushError("TREE_CATALOG_APPEND failure: " + failure);
        GD.PushError("TREE_CATALOG_APPEND=FAIL " + _failures.Count + " check(s)");
        return 1;
    }

    static string Json(object? value) => JsonSerializer.Serialize(value);
    static string Sha(string resPath) => Convert.ToHexString(SHA256.HashData(File.ReadAllBytes(ProjectSettings.GlobalizePath(resPath))));

    // ------------------------------------------------------------------ golden

    static void WriteBaseGolden()
    {
        IReadOnlyList<ImportedTreeVariant> catalog = ImportedTreeCatalog.Load();
        var variants = catalog.Take(30).Select(v => new
        {
            index = v.Index, name = v.Name, species = v.Species.ToString(),
            lod_hashes = v.Lods.Select(l => ImportedTreeRenderLodCatalog.HashLod((ArrayMesh)l)).ToArray()
        }).ToArray();
        // The identity strings are written out here with the pre-T6 interpolation, independent of VegetationIdentityDefinition.
        var identity = new List<object>();
        for (int i = 0; i < 8; i++)
        {
            (bool es, bool cm, bool wl) = (i % 2 == 1, (i / 2) % 2 == 1, (i / 4) % 2 == 1);
            ulong settings = 0x9E3779B97F4A7C15UL * (ulong)(i + 1);
            string text = FormattableString.Invariant($"v4|g8|seed1337|h1480032CB30B96CA|s{settings:X16}{(es ? "|es1" : "")}{(cm ? "|cm1" : "")}{(wl ? "|wl1" : "")}");
            identity.Add(new { tile = WorldGenerationFingerprint.TilePoses[i], settings = $"0x{settings:X16}", emitter_sites = es, climate_machines = cm, weather_lung = wl, definition = text });
        }
        var doc = new
        {
            schema = 1,
            note = "Generated by tree_catalog_append_test --write-base-golden from the prepared base files as they were BEFORE T6-5 changed anything (the base resources are unchanged by T6-5; sha256 of lolipop_catalog.res and lolipop_impostor_atlas.res recorded here). Identity strings were written with the pre-T6 interpolation: v4|g{generator}|seed{seed}|h{definition hash}|s{settings}[|es1][|cm1][|wl1].",
            base_catalog_sha256 = Sha(BaseResource), impostor_atlas_sha256 = Sha(ImpostorResource),
            generator = 8, seed = 1337, definition_hash = "0x1480032CB30B96CA",
            variants, identity_mask0 = identity
        };
        File.WriteAllText(ProjectSettings.GlobalizePath(BaseGoldenPath), JsonSerializer.Serialize(doc, Pretty) + "\n");
        Console.WriteLine("TREE_CATALOG_APPEND_GOLDEN_WRITTEN " + BaseGoldenPath);
    }

    // ------------------------------------------------------------------ a, b: fingerprint

    void FingerprintChecks(IReadOnlyList<ImportedTreeVariant> baseCatalog)
    {
        using JsonDocument golden = JsonDocument.Parse(File.ReadAllText(ProjectSettings.GlobalizePath(WorldGenerationFingerprintTest.GoldenPath)));
        JsonElement rows = golden.RootElement.GetProperty("rows");
        Dictionary<string, object?> catalogField = WorldGenerationFingerprint.ComputeCatalogField(baseCatalog);
        string recomputed = Json(catalogField);
        int checkedRows = 0;
        string gen1Catalog = "";
        WorldGenerationLedger ledger = WorldGenerationLedger.Production;
        foreach (JsonElement row in rows.EnumerateArray())
        {
            int generation = row.GetProperty("generation").GetInt32();
            string stored = JsonSerializer.Serialize(JsonSerializer.Deserialize<Dictionary<string, object?>>(row.GetProperty("catalog").GetRawText()));
            // Compare as parsed values: the golden's hash string and counts against the recomputed field.
            JsonElement c = row.GetProperty("catalog");
            Check(c.GetProperty("hash").GetString() == (string)catalogField["hash"]! && c.GetProperty("version").GetInt32() == (int)catalogField["version"]! && c.GetProperty("variant_count").GetInt32() == (int)catalogField["variant_count"]!,
                $"a. golden row {generation}: catalog field differs from the recomputed one ({stored} vs {recomputed})");
            Dictionary<string, object?> appended = WorldGenerationFingerprint.ComputeCatalogAppended(ledger.FeatureSet(generation, Array.Empty<string>()), ImportedTreeSourceTable.Production);
            if (row.TryGetProperty("catalog_appended", out JsonElement a))
                Check(a.GetProperty("hash").GetString() == (string)appended["hash"]! && a.GetProperty("count").GetInt32() == (int)appended["count"]!, $"a. golden row {generation}: catalog_appended differs");
            else
                Check((int)appended["count"]! == 0 && (string)appended["hash"]! == "none", $"a. golden row {generation} has no catalog_appended (= none) but the recomputed one is {Json(appended)}");
            if (generation == 1) gen1Catalog = c.GetProperty("hash").GetString()!;
            checkedRows++;
        }
        Check(checkedRows > 0 && gen1Catalog.Length > 0, "a. the golden has no generation 1 row");
        Detail($"a. {checkedRows} golden row(s): catalog equals the recomputed field (gen1 {gen1Catalog}) and catalog_appended is none for each frozen generation");

        // b. a synthetic row behind an unused feature
        var synthetic = new ImportedTreeSourceRow(55, TreeSpecies.Maple, TreeFormKind.Shrub, TreeSizeClass.Small, 1, TreePlacementRole.Shrub, TreeSourceCatalog.T6Derived, "synthetic", 6, NewSpecies);
        TreeSourceTable test = ImportedTreeSourceTable.CreateForTests(ImportedTreeSourceTable.Rows.Append(synthetic));
        IReadOnlySet<string> gen1 = ledger.FeatureSet(1, Array.Empty<string>());
        var structure = new HashSet<string>(gen1) { FeatureId };
        var both = new HashSet<string>(structure) { NewSpecies };
        var onlyNew = new HashSet<string>(gen1) { NewSpecies };
        string Appended(IReadOnlySet<string> set, TreeSourceTable table) => Json(WorldGenerationFingerprint.ComputeCatalogAppended(set, table));
        Check(Appended(gen1, test) == Appended(gen1, ImportedTreeSourceTable.Production), "b. the synthetic row changed generation 1's catalog_appended");
        Check(Appended(gen1, test) == Json(new Dictionary<string, object?> { ["count"] = 0, ["hash"] = "none" }), "b. generation 1's catalog_appended is not none");
        Check(Appended(structure, test) == Appended(structure, ImportedTreeSourceTable.Production), "b. the synthetic row changed catalog_appended for {forest_structure}");
        Check(Appended(both, test) != Appended(structure, test), "b. the synthetic row did not change catalog_appended for a set that enables it");
        Check(Appended(onlyNew, test) != Appended(gen1, test), "b. the synthetic row did not change catalog_appended for {new_species} alone");
        Check(Json(WorldGenerationFingerprint.ComputeCatalogField(baseCatalog)) == recomputed, "b. the catalog field changed");
        Dictionary<string, object?> withStructure = WorldGenerationFingerprint.ComputeCatalogAppended(structure, ImportedTreeSourceTable.Production);
        Check((int)withStructure["count"]! == DerivedTreeCatalog.FormCount, $"b. {{forest_structure}} does not append {DerivedTreeCatalog.FormCount} rows");
        Detail($"b. synthetic row 55: gen1 none unchanged; {{forest_structure}} count {withStructure["count"]} hash {withStructure["hash"]} unchanged; a set with {NewSpecies} changes it");
    }

    // ------------------------------------------------------------------ c: cache identity

    void IdentityChecks()
    {
        using JsonDocument doc = JsonDocument.Parse(File.ReadAllText(ProjectSettings.GlobalizePath(BaseGoldenPath)));
        JsonElement golden = doc.RootElement;
        int generator = golden.GetProperty("generator").GetInt32(), seed = golden.GetProperty("seed").GetInt32();
        ulong definition = Convert.ToUInt64(golden.GetProperty("definition_hash").GetString()!.Substring(2), 16);
        int n = 0;
        foreach (JsonElement e in golden.GetProperty("identity_mask0").EnumerateArray())
        {
            ulong settings = Convert.ToUInt64(e.GetProperty("settings").GetString()!.Substring(2), 16);
            string now = RingBiomeDecorationLayer.VegetationIdentityDefinition(generator, seed, definition, settings, e.GetProperty("emitter_sites").GetBoolean(), e.GetProperty("climate_machines").GetBoolean(), e.GetProperty("weather_lung").GetBoolean(), 0);
            Check(now == e.GetProperty("definition").GetString(), $"c. tile {e.GetProperty("tile").GetString()}: identity '{now}' differs from golden '{e.GetProperty("definition").GetString()}'");
            // Other bits change nothing (scatter bit 5); bit 6 appends |fs..|dc1 and nothing else.
            Check(RingBiomeDecorationLayer.VegetationIdentityDefinition(generator, seed, definition, settings, false, false, false, 1 << 5) == RingBiomeDecorationLayer.VegetationIdentityDefinition(generator, seed, definition, settings, false, false, false, 0), "c. bit 5 changed the identity");
            string on = RingBiomeDecorationLayer.VegetationIdentityDefinition(generator, seed, definition, settings, e.GetProperty("emitter_sites").GetBoolean(), e.GetProperty("climate_machines").GetBoolean(), e.GetProperty("weather_lung").GetBoolean(), 1 << 6);
            Check(on.StartsWith(now, StringComparison.Ordinal) && on.EndsWith("|dc" + DerivedTreeCatalog.CatalogVersion, StringComparison.Ordinal) && on.Contains("|fs"), $"c. bit 6 identity '{on}' is not the mask-0 string plus |fs..|dc{DerivedTreeCatalog.CatalogVersion}");
            n++;
        }
        Check(n == 8, "c. expected 8 golden identity strings, got " + n);
        Detail($"c. {n} generation 1 identity strings unchanged with the derived catalog loaded; bit 6 appends |fs..|dc{DerivedTreeCatalog.CatalogVersion}");
    }

    // ------------------------------------------------------------------ d: base golden

    void BaseGoldenChecks(IReadOnlyList<ImportedTreeVariant> baseCatalog)
    {
        using JsonDocument doc = JsonDocument.Parse(File.ReadAllText(ProjectSettings.GlobalizePath(BaseGoldenPath)));
        JsonElement golden = doc.RootElement;
        Check(Sha(BaseResource) == golden.GetProperty("base_catalog_sha256").GetString(), "d. lolipop_catalog.res sha256 differs from the golden");
        Check(Sha(ImpostorResource) == golden.GetProperty("impostor_atlas_sha256").GetString(), "d. lolipop_impostor_atlas.res sha256 differs from the golden");
        JsonElement[] variants = golden.GetProperty("variants").EnumerateArray().ToArray();
        Check(variants.Length == 30 && baseCatalog.Count == 30, $"d. golden has {variants.Length} variants, catalog {baseCatalog.Count}");
        for (int i = 0; i < Math.Min(variants.Length, baseCatalog.Count); i++)
        {
            ImportedTreeVariant v = baseCatalog[i];
            JsonElement g = variants[i];
            Check(g.GetProperty("index").GetInt32() == v.Index && g.GetProperty("name").GetString() == v.Name && g.GetProperty("species").GetString() == v.Species.ToString(), $"d. variant {i} identity differs ({v.Index} {v.Name} {v.Species})");
            JsonElement[] hashes = g.GetProperty("lod_hashes").EnumerateArray().ToArray();
            Check(hashes.Length == v.Lods.Length && v.Lods.Length == 4, $"d. variant {i} has {v.Lods.Length} LODs");
            for (int lod = 0; lod < Math.Min(hashes.Length, v.Lods.Length); lod++)
                Check(hashes[lod].GetString() == ImportedTreeRenderLodCatalog.HashLod((ArrayMesh)v.Lods[lod]), $"d. variant {i} ({v.Name}) LOD{lod} mesh hash differs from the golden");
        }
        Detail("d. 30 base variants (index, name, species, LOD0-LOD3 hashes) and the base and impostor resource sha256 match the golden");
    }

    // ------------------------------------------------------------------ e, f: structure and size

    void StructureChecks(IReadOnlyList<ImportedTreeVariant> baseCatalog)
    {
        IReadOnlyList<DerivedTreeForm> forms = DerivedTreeCatalog.Load();
        Check(forms.Count == DerivedTreeCatalog.FormCount && forms.Select(f => f.Index).SequenceEqual(Enumerable.Range(30, 25)), "e. derived indices are not 30-54 contiguous");
        var resource = ResourceLoader.Load<PreparedDerivedTreeCatalog>(DerivedTreeCatalog.ResourcePath);
        Check(resource.Meshes.Count == forms.Count * LodSlots, $"e. {resource.Meshes.Count} mesh slots, expected {forms.Count * LodSlots} (no LOD3 / impostor slot beyond LODF)");
        Check(forms.Take(6).All(f => f.Form == TreeFormKind.Snag) && forms.Skip(6).Take(4).All(f => f.Form == TreeFormKind.FallenTree) && forms.Skip(10).Take(3).All(f => f.Form == TreeFormKind.Stump) && forms.Skip(13).All(f => f.Form == TreeFormKind.Shrub), "e. form kinds are not snags 30-35, logs 36-39, stumps 40-42, shrubs 43-54");
        foreach (DerivedTreeForm f in forms)
        {
            ImportedTreeVariant source = baseCatalog[f.SourceBaseVariant];
            string id = $"form {f.Index} ({f.Form} of {source.Name})";
            Check(f.Species == source.Species && f.Materials.Count == 1, $"e. {id} species/materials");
            int expectedLods = f.Form == TreeFormKind.Stump ? 1 : f.Form == TreeFormKind.Shrub ? 2 : 4;
            for (int lod = 0; lod < LodSlots; lod++)
            {
                Mesh? mesh = f.Lods[lod];
                if (lod >= expectedLods) { Check(mesh == null, $"e. {id} LOD{lod} should be empty"); continue; }
                if (mesh == null) { Check(false, $"e. {id} LOD{lod} missing"); continue; }
                Check(mesh.GetSurfaceCount() == 1, $"e. {id} LOD{lod} has {mesh.GetSurfaceCount()} surfaces");
                Check(mesh.SurfaceGetMaterial(0) == f.Materials[0], $"e. {id} LOD{lod} lacks its material");
                Godot.Collections.Array a = mesh.SurfaceGetArrays(0);
                Vector3[] v = a[(int)Mesh.ArrayType.Vertex].AsVector3Array();
                int[] idx = a[(int)Mesh.ArrayType.Index].AsInt32Array();
                Check(idx.Length > 0 && idx.Length % 3 == 0 && idx.All(i => i >= 0 && i < v.Length), $"e. {id} LOD{lod} index array");
                Check(v.All(p => float.IsFinite(p.X) && float.IsFinite(p.Y) && float.IsFinite(p.Z)), $"e. {id} LOD{lod} non-finite vertex");
                Vector3[] nrm = a[(int)Mesh.ArrayType.Normal].AsVector3Array();
                Check(nrm.Length == v.Length && nrm.All(n => Math.Abs(n.Length() - 1f) < .02f), $"e. {id} LOD{lod} normals");
                Aabb box = mesh.GetAabb();
                int tris = idx.Length / 3;
                switch (f.Form)
                {
                    case TreeFormKind.Snag:
                        Check(box.Position.Y > -.01f && box.End.Y < 1.05f && box.End.Y > .5f, $"e. {id} LOD{lod} bounds y {box.Position.Y:F3}..{box.End.Y:F3}");
                        if (lod == 3) Check(tris is >= 50 and <= 110, $"e. {id} LODF has {tris} triangles");
                        break;
                    case TreeFormKind.FallenTree:
                        Check(box.Position.X <= -PrepareDerivedTreeAssets.LogClip * .5f + .03f && box.Position.X >= -PrepareDerivedTreeAssets.LogClip * .5f - .01f && Math.Abs(box.End.X - PrepareDerivedTreeAssets.LogClip * .5f) < .01f,
                            $"e. {id} LOD{lod} does not lie along +X centred at the origin (x {box.Position.X:F3}..{box.End.X:F3})");
                        float reach2 = 2f * PrepareDerivedTreeAssets.LogReach * source.TrunkRadiusMeters / source.HeightMeters + .002f; // 2 R plus a small tolerance, R = 3 x trunk radius (normalised)
                        Check(lod == 3 || (box.Size.Y <= reach2 && box.Size.Z <= reach2), $"e. {id} LOD{lod} lateral extent {box.Size.Y:F3} x {box.Size.Z:F3} exceeds 2R + 0.002 = {reach2:F3}");
                        if (lod == 3) Check(tris is >= 30 and <= 110, $"e. {id} LODF has {tris} triangles");
                        break;
                    case TreeFormKind.Shrub:
                        // One surface in the source species' foliage material (alpha cutout), normalised space: 1 unit tall, on the ground, wind attachments (Custom0) = (x, 0, z, 1), UVs inside the atlas.
                        Check(f.Materials[0].GetShaderParameter("use_alpha_cutout").AsBool() && f.Materials[0].GetShaderParameter("tree_foliage_mode").AsInt32() == 1, $"e. {id} LOD{lod} is not in an alpha-cutout foliage material");
                        Check(Math.Abs(box.End.Y - 1f) < .001f && box.Position.Y > -.001f && box.Position.Y < .35f, $"e. {id} LOD{lod} bounds y {box.Position.Y:F3}..{box.End.Y:F3} (expected 1 unit tall on the ground)");
                        Check(box.Size.X > .6f && box.Size.X < 2.2f && box.Size.Z > .6f && box.Size.Z < 2.2f, $"e. {id} LOD{lod} footprint {box.Size.X:F2} x {box.Size.Z:F2}");
                        Check(lod == 0 ? tris == (source.Species == TreeSpecies.Maple ? 28 : source.Species == TreeSpecies.Pine ? 20 : 24) : tris == 8, $"e. {id} LOD{lod} has {tris} triangles");
                        float[] attach = a[(int)Mesh.ArrayType.Custom0].AsFloat32Array();
                        Vector2[] uvs = a[(int)Mesh.ArrayType.TexUV].AsVector2Array();
                        bool attachOk = attach.Length == v.Length * 4, uvOk = uvs.Length == v.Length;
                        for (int k = 0; attachOk && k < v.Length; k++) attachOk = Math.Abs(attach[k * 4] - v[k].X) < 1e-5f && attach[k * 4 + 1] == 0f && Math.Abs(attach[k * 4 + 2] - v[k].Z) < 1e-5f && attach[k * 4 + 3] == 1f;
                        foreach (Vector2 uv in uvs) uvOk &= uv.X >= 0f && uv.X <= 1f && uv.Y >= 0f && uv.Y <= 1f;
                        Check(attachOk, $"e. {id} LOD{lod} wind attachments are not (x, 0, z, 1)");
                        Check(uvOk, $"e. {id} LOD{lod} has UVs outside the atlas");
                        break;
                    case TreeFormKind.Stump:
                        float topM = box.End.Y * source.HeightMeters, bottomM = box.Position.Y * source.HeightMeters;
                        Check(topM >= .54f && topM <= .64f && Math.Abs(bottomM + .15f) < .002f, $"e. {id} stump spans {bottomM:F3}..{topM:F3} m, expected -0.15..0.54-0.64 m");
                        break;
                }
            }
            bool windOff = f.Form is TreeFormKind.FallenTree or TreeFormKind.Stump;
            Variant wind = f.Materials[0].GetShaderParameter("vegetation_wind_enabled");
            Check(windOff ? (wind.VariantType == Variant.Type.Bool && !wind.AsBool()) : (wind.VariantType == Variant.Type.Nil || wind.AsBool()), $"e. {id} wind flag (off for logs and stumps, on for snags)");
            Variant sourceWind = source.Lods[0].SurfaceGetMaterial(0) is ShaderMaterial sm ? sm.GetShaderParameter("vegetation_wind_enabled") : default;
            Check(sourceWind.VariantType == Variant.Type.Nil || sourceWind.AsBool(), $"e. {id} switched wind off on the base material");
            Check(f.Materials[0] != source.Lods[0].SurfaceGetMaterial(0), $"e. {id} shares the base bark material instead of a duplicate");
        }
        long bytes = new FileInfo(ProjectSettings.GlobalizePath(DerivedTreeCatalog.ResourcePath)).Length;
        Check(bytes < 8L * 1024 * 1024, $"f. derived resource is {bytes} bytes (limit 8 MiB)");
        Detail($"e. 25 forms 30-54 contiguous, snags/logs 4 LOD slots, stumps 1, shrubs 2, one surface each, bounds sane; f. derived resource {bytes} bytes");
    }

    // ------------------------------------------------------------------ g: regeneration

    void RegenerationChecks(IReadOnlyList<ImportedTreeVariant> baseCatalog)
    {
        PrepareDerivedTreeAssets.Result built = PrepareDerivedTreeAssets.Build(baseCatalog);
        using JsonDocument doc = JsonDocument.Parse(File.ReadAllText(ProjectSettings.GlobalizePath(PrepareDerivedTreeAssets.ManifestPath)));
        JsonElement manifest = doc.RootElement;
        Check(manifest.GetProperty("catalog_version").GetInt32() == DerivedTreeCatalog.CatalogVersion && manifest.GetProperty("form_count").GetInt32() == DerivedTreeCatalog.FormCount, "g. manifest catalog_version / form_count");
        Check(manifest.GetProperty("artifact_sha256").GetString() == Sha(DerivedTreeCatalog.ResourcePath), "g. manifest artifact_sha256 differs from the resource file");
        Check(manifest.GetProperty("total_bytes").GetInt64() == new FileInfo(ProjectSettings.GlobalizePath(DerivedTreeCatalog.ResourcePath)).Length, "g. manifest total_bytes");
        Check(manifest.GetProperty("base_catalog_artifact_sha256").GetString() == PrepareDerivedTreeAssets.ReadBaseArtifactSha() && PrepareDerivedTreeAssets.ReadBaseArtifactSha() == Sha(BaseResource), "g. manifest base catalog sha256 differs from the base manifest or file");
        JsonElement[] forms = manifest.GetProperty("forms").EnumerateArray().ToArray();
        Check(forms.Length == DerivedTreeCatalog.FormCount, "g. manifest form count " + forms.Length);
        int compared = 0;
        for (int f = 0; f < Math.Min(forms.Length, built.Resource.FormIndices.Length); f++)
        {
            Check(forms[f].GetProperty("index").GetInt32() == built.Resource.FormIndices[f] && forms[f].GetProperty("source_variant").GetInt32() == built.Resource.SourceVariants[f], $"g. manifest form {f} identity");
            foreach (JsonElement lod in forms[f].GetProperty("lods").EnumerateArray())
            {
                string name = lod.GetProperty("lod").GetString()!;
                int slot = f * LodSlots + (name == "F" ? PrepareDerivedTreeAssets.LodF : int.Parse(name));
                ArrayMesh? mesh = built.Resource.Meshes[slot];
                Check(mesh != null && ImportedTreeRenderLodCatalog.HashLod(mesh) == lod.GetProperty("mesh_hash").GetString(), $"g. form {built.Resource.FormIndices[f]} LOD{name} regenerated mesh hash differs from the manifest");
                Check(lod.GetProperty("source_hash").GetString() == built.Resource.SourceHashes[slot], $"g. form {built.Resource.FormIndices[f]} LOD{name} source hash differs");
                compared++;
            }
        }
        Check(compared == built.Resource.Meshes.Count(m => m != null), $"g. compared {compared} LOD entries");
        Detail($"g. regenerated {compared} meshes in process: hashes equal the manifest");

        // h. forms 30-42 keep the mesh hashes T6-5 wrote (the shrubs only append).
        using JsonDocument goldenDoc = JsonDocument.Parse(File.ReadAllText(ProjectSettings.GlobalizePath(DerivedGoldenPath)));
        int held = 0;
        foreach (JsonElement form in goldenDoc.RootElement.GetProperty("forms").EnumerateArray())
        {
            int index = form.GetProperty("index").GetInt32();
            int slot = Array.IndexOf(built.Resource.FormIndices, index);
            Check(slot >= 0 && slot < 13, $"h. form {index} is not in the regenerated catalog first 13 slots");
            if (slot < 0) continue;
            foreach (JsonElement lod in form.GetProperty("lods").EnumerateArray())
            {
                string name = lod.GetProperty("lod").GetString()!;
                ArrayMesh? mesh = built.Resource.Meshes[slot * LodSlots + (name == "F" ? PrepareDerivedTreeAssets.LodF : int.Parse(name))];
                Check(mesh != null && ImportedTreeRenderLodCatalog.HashLod(mesh) == lod.GetProperty("mesh_hash").GetString(), $"h. form {index} LOD{name} mesh hash differs from the T6-5 golden (forms 30-42 must not change)");
                Check(lod.GetProperty("source_hash").GetString() == built.Resource.SourceHashes[slot * LodSlots + (name == "F" ? PrepareDerivedTreeAssets.LodF : int.Parse(name))], $"h. form {index} LOD{name} source hash differs from the T6-5 golden");
                held++;
            }
        }
        Detail($"h. forms 30-42: {held} mesh hashes equal the T6-5 golden");

        // i. the shrubs: the manifest's cluster rectangles are what the tool finds now, per species (maple, fir, pine), and every shrub form has meshes in slots 0 and 1 only.
        JsonElement clusters = manifest.GetProperty("shrub_clusters");
        int rectangles = 0;
        foreach (JsonElement c in clusters.EnumerateArray())
        {
            var species = Enum.Parse<TreeSpecies>(c.GetProperty("species").GetString()!);
            var atlas = Image.LoadFromFile(ProjectSettings.GlobalizePath(PrepareDerivedTreeAssets.AtlasPath(species)));
            List<PrepareDerivedTreeAssets.ClusterRect> found = PrepareDerivedTreeAssets.ClusterRectangles(baseCatalog, species, atlas);
            JsonElement[] used = c.GetProperty("used").EnumerateArray().ToArray();
            Check(found.Count == used.Length && found.Count >= 3, $"i. {species}: {found.Count} cluster rectangles found, manifest has {used.Length} (at least 3 needed)");
            for (int k = 0; k < Math.Min(found.Count, used.Length); k++)
                Check(Math.Abs(found[k].U0 - used[k].GetProperty("u0").GetSingle()) < 1e-4f && Math.Abs(found[k].V1 - used[k].GetProperty("v1").GetSingle()) < 1e-4f, $"i. {species}: cluster rectangle {k} differs from the manifest");
            Check(found.Count <= PrepareDerivedTreeAssets.MaxClusters, $"i. {species}: more than {PrepareDerivedTreeAssets.MaxClusters} rectangles");
            rectangles += found.Count;
            Detail($"i. {species} ({PrepareDerivedTreeAssets.LookOf(species)}): {found.Count} cluster rectangles, regenerated equal to the manifest");
        }
        Check(clusters.GetArrayLength() == 3, "i. the manifest does not hold three cluster sets");
        for (int f = 13; f < built.Resource.FormIndices.Length; f++)
            for (int lod = 0; lod < LodSlots; lod++)
                Check((built.Resource.Meshes[f * LodSlots + lod] != null) == (lod < 2), $"i. shrub form {built.Resource.FormIndices[f]} slot {lod} {(lod < 2 ? "empty" : "filled")}");
        Detail($"i. {rectangles} cluster rectangles in total; shrub forms 43-54 fill slots 0 and 1");
    }
